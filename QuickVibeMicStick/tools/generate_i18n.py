#!/usr/bin/env python3
"""Generate firmware and Host language tables from res/i18n/*.json."""

from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
RESOURCE_DIR = ROOT / "QuickVibeMicStick" / "res" / "i18n"
FIRMWARE_HEADER = ROOT / "QuickVibeMicStick" / "i18n_catalog.generated.h"
FIRMWARE_SOURCE = ROOT / "QuickVibeMicStick" / "i18n_catalog.generated.cpp"
HOST_SOURCE = ROOT / "QuickVibeHost" / "QuickVibeHost" / "DeviceI18n.generated.swift"
LOCALES = ("en", "zh-Hans", "zh-Hant")


def load_catalogs() -> dict[str, dict[str, str]]:
    catalogs = {
        locale: json.loads((RESOURCE_DIR / f"{locale}.json").read_text(encoding="utf-8"))
        for locale in LOCALES
    }
    expected = list(catalogs["en"])
    for locale, catalog in catalogs.items():
        if list(catalog) != expected:
            missing = sorted(set(expected) - set(catalog))
            extra = sorted(set(catalog) - set(expected))
            raise SystemExit(f"{locale}: key/order mismatch; missing={missing}, extra={extra}")
    placeholder_pattern = re.compile(r"%(?:[-+0 #]*\d*(?:\.\d+)?[hljztL]*)?[A-Za-z%]")
    for key in expected:
        placeholders = [placeholder_pattern.findall(catalogs[locale][key]) for locale in LOCALES]
        if placeholders[1:] != placeholders[:1] * (len(placeholders) - 1):
            raise SystemExit(f"{key}: printf placeholder mismatch: {placeholders}")
    for locale, catalog in catalogs.items():
        for key, value in catalog.items():
            if not key.startswith("action."):
                continue
            limit = 24 if key.endswith(".title") else 48
            size = len(value.encode("utf-8"))
            if size > limit:
                raise SystemExit(f"{locale}:{key}: {size} UTF-8 bytes exceeds protocol limit {limit}")
    return catalogs


def enum_name(key: str) -> str:
    return "UI_STR_" + re.sub(r"[^A-Za-z0-9]+", "_", key).upper()


def c_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def swift_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False).replace("\\/", "/")


def generate_firmware(catalogs: dict[str, dict[str, str]]) -> None:
    keys = list(catalogs["en"])
    header = """// Generated by tools/generate_i18n.py. Do not edit by hand.
#pragma once

#include <stdint.h>

enum UiLocale : uint8_t {
    UI_LOCALE_EN = 0,
    UI_LOCALE_ZH_HANS = 1,
    UI_LOCALE_ZH_HANT = 2,
    UI_LOCALE_COUNT = 3,
};

enum UiStringId : uint8_t {
"""
    header += "\n".join(f"    {enum_name(key)}," for key in keys)
    header += """
    UI_STR_COUNT,
};

bool i18nSetLocale(uint8_t locale);
UiLocale i18nGetLocale();
const char *i18nText(UiStringId id);
const char *i18nTextFor(UiStringId id, UiLocale locale);
"""

    source = """// Generated by tools/generate_i18n.py. Do not edit by hand.
#include "i18n_catalog.generated.h"

static UiLocale s_locale = UI_LOCALE_EN;

static const char *const kCatalog[UI_LOCALE_COUNT][UI_STR_COUNT] = {
"""
    for locale in LOCALES:
        source += "    {\n"
        source += "\n".join(f"        {c_string(catalogs[locale][key])}," for key in keys)
        source += "\n    },\n"
    source += """};

bool i18nSetLocale(uint8_t locale) {
    if (locale >= UI_LOCALE_COUNT) return false;
    s_locale = static_cast<UiLocale>(locale);
    return true;
}

UiLocale i18nGetLocale() {
    return s_locale;
}

const char *i18nTextFor(UiStringId id, UiLocale locale) {
    if (id >= UI_STR_COUNT) return "";
    if (locale >= UI_LOCALE_COUNT) locale = UI_LOCALE_EN;
    const char *value = kCatalog[locale][id];
    return (value && value[0]) ? value : kCatalog[UI_LOCALE_EN][id];
}

const char *i18nText(UiStringId id) {
    return i18nTextFor(id, s_locale);
}
"""
    FIRMWARE_HEADER.write_text(header, encoding="utf-8")
    FIRMWARE_SOURCE.write_text(source, encoding="utf-8")


def generate_host(catalogs: dict[str, dict[str, str]]) -> None:
    action_keys = [key for key in catalogs["en"] if key.startswith("action.")]
    source = """// Generated by QuickVibeMicStick/tools/generate_i18n.py. Do not edit by hand.
import Foundation

enum DeviceDisplayLanguage: Int, CaseIterable, Identifiable {
    case english = 0
    case simplifiedChinese = 1
    case traditionalChinese = 2

    var id: Int { rawValue }
    var protocolValue: UInt8 { UInt8(rawValue) }

    var displayName: String {
        switch self {
        case .english: return "English"
        case .simplifiedChinese: return "简体中文"
        case .traditionalChinese: return "繁體中文"
        }
    }

    static var selected: DeviceDisplayLanguage {
        let appLanguage = AppLanguage(
            rawValue: UserDefaults.standard.string(forKey: AppLanguageSettings.userDefaultsKey) ?? ""
        ) ?? .system
        switch appLanguage {
        case .en: return .english
        case .zhHans: return .simplifiedChinese
        case .zhHant: return .traditionalChinese
        case .system:
            let preferred = (Bundle.main.preferredLocalizations.first
                             ?? Locale.preferredLanguages.first
                             ?? "en").lowercased()
            if preferred.hasPrefix("zh-hant") || preferred.hasPrefix("zh-tw")
                || preferred.hasPrefix("zh-hk") || preferred.hasPrefix("zh-mo") {
                return .traditionalChinese
            }
            return preferred.hasPrefix("zh") ? .simplifiedChinese : .english
        }
    }
}

enum DeviceI18n {
    private static let actionCatalogs: [[String: String]] = [
"""
    for locale in LOCALES:
        source += "        [\n"
        source += "\n".join(
            f"            {swift_string(key)}: {swift_string(catalogs[locale][key])},"
            for key in action_keys
        )
        source += "\n        ],\n"
    source += """    ]

    static func action(_ key: String, language: DeviceDisplayLanguage) -> String {
        actionCatalogs[language.rawValue][key] ?? actionCatalogs[0][key] ?? key
    }
}
"""
    HOST_SOURCE.write_text(source, encoding="utf-8")


def main() -> None:
    catalogs = load_catalogs()
    generate_firmware(catalogs)
    generate_host(catalogs)
    print(f"Generated {len(catalogs['en'])} firmware strings and Host action catalogs.")


if __name__ == "__main__":
    main()

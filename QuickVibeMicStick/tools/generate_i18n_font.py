#!/usr/bin/env python3
"""Build GB2312 + localized UI glyph fonts from an upstream U8g2 checkout."""

from __future__ import annotations

import argparse
import json
import subprocess
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
RESOURCE_DIR = ROOT / "QuickVibeMicStick" / "res" / "i18n"
HEADER_PATH = ROOT / "QuickVibeMicStick" / "i18n_font.generated.h"
SOURCE_PATH = ROOT / "QuickVibeMicStick" / "i18n_font.generated.cpp"
COVERAGE_PATH = ROOT / "QuickVibeMicStick" / "i18n_font_coverage.generated.json"
LOCALES = ("en", "zh-Hans", "zh-Hant")


def localized_characters() -> str:
    characters: set[str] = set()
    for locale in LOCALES:
        catalog = json.loads((RESOURCE_DIR / f"{locale}.json").read_text(encoding="utf-8"))
        for value in catalog.values():
            characters.update(value)
    return "".join(sorted(characters, key=ord))


def build_converter(u8g2_root: Path) -> Path:
    directory = u8g2_root / "tools" / "font" / "bdfconv"
    executable = directory / "bdfconv"
    if not executable.exists():
        subprocess.run(
            ["make", "CFLAGS=-O3 -Wall -Werror"],
            cwd=directory,
            check=True,
        )
    return executable


def generate_font(converter: Path, u8g2_root: Path, bdf_name: str,
                  symbol: str, characters_file: Path, output: Path) -> None:
    font_root = u8g2_root / "tools" / "font"
    subprocess.run(
        [
            str(converter),
            str(font_root / "bdf" / bdf_name),
            "-g", "32", "-b", "0", "-f", "1",
            "-M", str(font_root / "build" / "gb2312.map"),
            "-u", str(characters_file),
            "-n", symbol,
            "-o", str(output),
        ],
        check=True,
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--u8g2-root",
        type=Path,
        required=True,
        help="U8g2 source checkout containing tools/font/bdfconv and WenQuanYi BDF files",
    )
    args = parser.parse_args()
    u8g2_root = args.u8g2_root.resolve()
    converter = build_converter(u8g2_root)

    symbols = (
        ("wenquanyi_9pt.bdf", "u8g2_font_qvms12_t_i18n"),
        ("wenquanyi_12pt.bdf", "u8g2_font_qvms16_t_i18n"),
    )
    with tempfile.TemporaryDirectory(prefix="qvms-i18n-font-") as temp:
        temp_dir = Path(temp)
        characters_file = temp_dir / "characters.txt"
        characters_file.write_text(localized_characters(), encoding="utf-8")
        generated_parts: list[str] = []
        for index, (bdf_name, symbol) in enumerate(symbols):
            output = temp_dir / f"font-{index}.c"
            generate_font(converter, u8g2_root, bdf_name, symbol, characters_file, output)
            generated = output.read_text(encoding="utf-8")
            generated_parts.append("\n".join(line.rstrip() for line in generated.splitlines()) + "\n")

    HEADER_PATH.write_text(
        """// Generated by tools/generate_i18n_font.py. Do not edit by hand.
#pragma once

#include <stdint.h>

extern const uint8_t u8g2_font_qvms12_t_i18n[];
extern const uint8_t u8g2_font_qvms16_t_i18n[];
""",
        encoding="utf-8",
    )
    preamble = """// Generated by tools/generate_i18n_font.py. Do not edit by hand.
// Source: WenQuanYi Bitmap Song 0.9.9.8, GPL-2.0 with font embedding exception.
#include "i18n_font.generated.h"

#ifndef U8G2_FONT_SECTION
#define U8G2_FONT_SECTION(name)
#endif
#ifndef U8G2_USE_LARGE_FONTS
#define U8G2_USE_LARGE_FONTS
#endif

"""
    SOURCE_PATH.write_text(preamble + "\n".join(generated_parts), encoding="utf-8")
    characters = localized_characters()
    COVERAGE_PATH.write_text(
        json.dumps(
            {
                "source": "WenQuanYi Bitmap Song 0.9.9.8",
                "baseCoverage": "GB2312",
                "localizedCodepoints": [f"U+{ord(character):04X}" for character in characters],
            },
            ensure_ascii=False,
            indent=2,
        ) + "\n",
        encoding="utf-8",
    )
    print(f"Generated {len(characters)} localized characters plus GB2312 coverage.")


if __name__ == "__main__":
    main()
